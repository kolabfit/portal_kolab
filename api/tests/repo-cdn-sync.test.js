import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import crypto from 'node:crypto';
import mysql from 'mysql2/promise';
import dotenv from 'dotenv';

test('repository sync imports, updates, hides, restores and preserves data during outages', async t => {
  dotenv.config({ path: new URL('../.env', import.meta.url), quiet: true });
  const database = `portal_cdn_sync_test_${crypto.randomBytes(6).toString('hex')}`;
  const control = await mysql.createConnection({ host: process.env.DB_HOST, port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER, password: process.env.DB_PASSWORD });
  await control.query(`CREATE DATABASE \`${database}\``);
  let db;
  let inventory = [{ id: 'remote1', project_id: 'test-project', name: 'photo.png', size: 12, mime_type: 'image/png', status: 'ready' }];
  let outage = false;
  const server = http.createServer((req, res) => {
    res.writeHead(outage ? 503 : 200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(outage ? { error: 'Unavailable' } : inventory));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => {
    await db?.end();
    await new Promise(resolve => server.close(resolve));
    await control.query(`DROP DATABASE \`${database}\``);
    await control.end();
  });
  process.env.DB_NAME = database;
  process.env.KROOMBOX_CDN_BASE_URL = `http://127.0.0.1:${server.address().port}`;
  process.env.KROOMBOX_CDN_PROJECT_ID = 'test-project';
  process.env.KROOMBOX_CDN_API_KEY = 'test';
  process.env.KROOMBOX_CDN_JWT = '';
  process.env.KROOMBOX_CDN_SYNC_ENABLED = 'true';
  db = (await import('../lib/db.js')).default;
  await db.query(`CREATE TABLE repo (id VARCHAR(100) PRIMARY KEY,name VARCHAR(255),url TEXT,date DATETIME,size BIGINT,mime VARCHAR(100),category VARCHAR(50),owner_id VARCHAR(100),role VARCHAR(20),parent_id VARCHAR(100),type VARCHAR(20),cdn_asset_id VARCHAR(50),storage_provider VARCHAR(30))`);
  await db.query(`CREATE TABLE cdn_assets (id VARCHAR(50) PRIMARY KEY,cdn_file_id VARCHAR(255),owner_id VARCHAR(100),owner_role VARCHAR(20),feature_type VARCHAR(50),feature_id VARCHAR(100),original_name VARCHAR(255),mime_type VARCHAR(100),file_size BIGINT,cdn_delivery_url TEXT,cdn_status VARCHAR(30),is_private BOOLEAN,storage_provider VARCHAR(30),created_by VARCHAR(100),deleted_at TIMESTAMP NULL)`);
  const { syncRepositoryCdn } = await import('../lib/repoCdnSync.js');
  const { listRepository } = await import('../lib/repository.js');
  let now = Date.now();
  t.mock.method(Date, 'now', () => now);
  const sync = async () => { now += 31000; return syncRepositoryCdn(); };
  const admin = { id: 'ROOT', role: 'ADMIN' };

  assert.equal((await sync()).status, 'success');
  let result = await listRepository(admin, true, 'http://portal.test/api');
  assert.equal(result.items.length, 1);
  assert.equal(result.items[0].ownerId, 'ROOT');
  assert.equal(result.items[0].url, 'http://portal.test/api/files/cdn-remote1');
  assert.equal((await listRepository({ id: 'student', role: 'STUDENT' })).items.length, 0);
  assert.equal((await sync()).status, 'success');
  assert.equal((await listRepository(admin, true)).items.length, 1, 'import is idempotent');
  await db.execute("UPDATE repo SET owner_id='student',role='STUDENT',date=NOW()-INTERVAL 10 MINUTE");
  inventory[0].name = 'renamed.png'; inventory[0].size = 24;
  await sync();
  result = await listRepository({ id: 'student', role: 'STUDENT' });
  assert.equal(result.items[0].name, 'renamed.png');
  assert.equal(result.globalStats.usedSpace, 24);
  const saved = inventory;
  inventory = [];
  await sync();
  assert.equal((await listRepository(admin, true)).items.length, 1, 'one missing snapshot is insufficient');
  outage = true;
  assert.equal((await sync()).status, 'unavailable');
  assert.equal((await listRepository(admin, true)).items.length, 1);
  outage = false;
  await sync();
  assert.equal((await listRepository(admin, true)).items.length, 1, 'outage resets missing confirmation');
  await sync();
  result = await listRepository(admin, true);
  assert.equal(result.items.length, 0);
  assert.equal(result.globalStats.usedSpace, 0);
  inventory = saved;
  await sync();
  assert.equal((await listRepository({ id: 'student', role: 'STUDENT' })).items.length, 1, 'restoration preserves owner');
  inventory = { files: [], total: 1 };
  assert.equal((await sync()).status, 'unavailable');
  assert.equal((await listRepository(admin, true)).items.length, 1, 'partial inventory cannot remove files');
});
